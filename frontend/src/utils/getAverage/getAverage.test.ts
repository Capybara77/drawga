import { describe, it, expect } from 'vitest';
import { average } from './getAverage'; // Указываем правильный путь к файлу с функцией

describe('average', () => {
  it('возвращает среднее значение двух положительных чисел', () => {
    expect(average(4, 6)).toBe(5);
  });

  it('возвращает среднее значение двух отрицательных чисел', () => {
    expect(average(-4, -6)).toBe(-5);
  });

  it('возвращает среднее значение положительного и отрицательного числа', () => {
    expect(average(10, -10)).toBe(0);
  });

  it('возвращает среднее значение двух одинаковых чисел', () => {
    expect(average(7, 7)).toBe(7);
  });

  it('возвращает правильное значение для нуля', () => {
    expect(average(0, 0)).toBe(0);
  });

  it('работает с дробными числами', () => {
    expect(average(2.5, 3.5)).toBe(3);
  });
});
